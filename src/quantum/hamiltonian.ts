/**
 * Time-independent single-qubit Hamiltonians (ħ = 1):
 *
 *   H = ω̄ I + ε X + Δω Z = ω̄ I + r (v·σ),   r = √(ε² + Δω²),   v = (ε, 0, Δω)/r
 *   U_t = e^{−iHt} = e^{−iω̄t} (cos(rt) I − i sin(rt) v·σ) = e^{−iω̄t} R_v(2rt)
 *
 * In terms of the level frequencies: H = diag(ω₁, ω₂) + εX with
 *   ω̄ = (ω₁ + ω₂)/2,  Δω = (ω₁ − ω₂)/2.
 */
import { Complex, c, expi, mul, abs2, ZERO } from './complex';
import { Mat2, Vec2, Vec3, I2, mat, matScale, matAdd, nDotSigma, apply, KET0, KET1, inner } from './linalg';
import { blochVector } from './bloch';

export interface HamiltonianParams {
  /** mean energy ω̄ (coefficient of I) */
  omegaBar: number;
  /** energy difference Δω (coefficient of Z) */
  deltaOmega: number;
  /** perturbation strength ε (coefficient of X) */
  epsilon: number;
}

export const fromOmegas = (omega1: number, omega2: number, epsilon = 0): HamiltonianParams => ({
  omegaBar: (omega1 + omega2) / 2,
  deltaOmega: (omega1 - omega2) / 2,
  epsilon,
});

export const toOmegas = (p: HamiltonianParams) => ({
  omega1: p.omegaBar + p.deltaOmega,
  omega2: p.omegaBar - p.deltaOmega,
});

export function hamiltonianMatrix(p: HamiltonianParams): Mat2 {
  return mat(c(p.omegaBar + p.deltaOmega), c(p.epsilon), c(p.epsilon), c(p.omegaBar - p.deltaOmega));
}

/** r = √(ε² + Δω²) and the unit axis v (null when r = 0, i.e. H ∝ I). */
export function hamiltonianAxis(p: HamiltonianParams, tol = 1e-12): { r: number; v: Vec3 | null } {
  const r = Math.hypot(p.epsilon, p.deltaOmega);
  if (r < tol) return { r: 0, v: null };
  return { r, v: [p.epsilon / r, 0, p.deltaOmega / r] };
}

/** Eigenvalues ω̄ ∓ r (ascending). */
export function energies(p: HamiltonianParams): [number, number] {
  const { r } = hamiltonianAxis(p);
  return [p.omegaBar - r, p.omegaBar + r];
}

/** U_t = e^{−iHt}, evaluated analytically (handles the degenerate case r = 0). */
export function evolutionOperator(p: HamiltonianParams, t: number): Mat2 {
  const { r, v } = hamiltonianAxis(p);
  const phase = expi(-p.omegaBar * t);
  if (!v) return matScale(I2, phase);
  const inner2 = matAdd(matScale(I2, c(Math.cos(r * t))), matScale(nDotSigma(v), c(0, -Math.sin(r * t))));
  return matScale(inner2, phase);
}

export const evolveState = (p: HamiltonianParams, psi0: Vec2, t: number): Vec2 =>
  apply(evolutionOperator(p, t), psi0);

/** Bloch rotation angle 2rt generated by the Pauli part of H. */
export const evolutionAngle = (p: HamiltonianParams, t: number): number => 2 * hamiltonianAxis(p).r * t;

/** ⟨1|ψ(t)⟩ for ψ(0) = |0⟩:  −i e^{−iω̄t} (ε/r) sin(rt). */
export function transitionAmplitude(p: HamiltonianParams, t: number): Complex {
  const { r } = hamiltonianAxis(p);
  if (r === 0) return ZERO;
  return mul(c(0, -(p.epsilon / r) * Math.sin(r * t)), expi(-p.omegaBar * t));
}

/** P(1, t) = ε²/(Δω² + ε²) · sin²(t √(Δω² + ε²)) for ψ(0) = |0⟩. */
export function transitionProbability(p: HamiltonianParams, t: number): number {
  const r2 = p.epsilon ** 2 + p.deltaOmega ** 2;
  if (r2 === 0) return 0;
  return (p.epsilon ** 2 / r2) * Math.sin(t * Math.sqrt(r2)) ** 2;
}

/** Oscillation characteristics of P(1,t) starting from |0⟩. */
export function oscillation(p: HamiltonianParams) {
  const { r } = hamiltonianAxis(p);
  const r2 = r * r;
  return {
    r,
    /** max_t P(1,t) = ε²/r² */
    maxTransition: r2 === 0 ? 0 : p.epsilon ** 2 / r2,
    /** sin²(rt) has period π/r */
    period: r === 0 ? Infinity : Math.PI / r,
    /** angular frequency of the Bloch-vector precession */
    blochAngularFrequency: 2 * r,
  };
}

export interface TrajectoryPoint {
  t: number;
  psi: Vec2;
  bloch: Vec3;
  p0: number;
  p1: number;
}

export function sampleTrajectory(p: HamiltonianParams, psi0: Vec2, tMax: number, n = 240): TrajectoryPoint[] {
  const out: TrajectoryPoint[] = [];
  for (let k = 0; k <= n; k++) {
    const t = (tMax * k) / n;
    const psi = evolveState(p, psi0, t);
    out.push({ t, psi, bloch: blochVector(psi), p0: abs2(inner(KET0, psi)), p1: abs2(inner(KET1, psi)) });
  }
  return out;
}
